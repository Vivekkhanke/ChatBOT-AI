CREATE TABLE CUSTOMER1
(
    CUSTOMER_ID NUMBER
        GENERATED BY DEFAULT AS IDENTITY
        PRIMARY KEY,

    CUSTOMER_NAME VARCHAR2(100)
        NOT NULL,

    EMAIL VARCHAR2(200),

    PHONE VARCHAR2(30),

    CREDIT_SCORE NUMBER(3),

    CREATED_DATE DATE
        DEFAULT SYSDATE
);


CREATE TABLE ACCOUNT_DETAILS
(
    ACCOUNT_ID NUMBER
        GENERATED BY DEFAULT AS IDENTITY
        PRIMARY KEY,

    CUSTOMER_ID NUMBER
        NOT NULL,

    ACCOUNT_TYPE VARCHAR2(50),

    ACCOUNT_NUMBER VARCHAR2(50),

    BALANCE NUMBER(18,2),

    LOAN_BALANCE NUMBER(18,2),

    CREDIT_CARD_BALANCE NUMBER(18,2),

    STATUS VARCHAR2(30),

    CONSTRAINT FK_ACCOUNT_CUSTOMER
        FOREIGN KEY
        (
            CUSTOMER_ID
        )
        REFERENCES CUSTOMER1
        (
            CUSTOMER_ID
        )
);


